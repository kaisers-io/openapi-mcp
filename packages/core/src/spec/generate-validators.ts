// Generates the precompiled OpenAPI meta-schema validators in ./generated/
// (issue #76). Compiling the official 3.0/3.1 meta-schemas with Ajv took about
// 120 ms on every run that processed a spec (a third of `tools --spec
// petstore`); the generated standalone code loads in under 10 ms and
// validates identically, because it IS what Ajv compiles, emitted as source.
//
// Regenerate after bumping ajv, ajv-formats, ajv-draft-04 or
// @seriousme/openapi-schema-validator:
//
//   node scripts/generate-validators.ts
//
// The write step lives in scripts/, outside src: it never runs in tests (so
// it would only drag this file under the coverage floor), and it can never be
// reached from the bundled CLI, where `import.meta.url` would point at dist.
//
// validate.test.ts fails while the committed files differ from what this
// produces, so a dependency bump cannot silently leave them stale.

import { createRequire } from 'node:module';
import type { Options, ValidateFunction } from 'ajv';
import type { OpenapiVersion } from './validate.ts';

type GeneratorAjv = {
  addFormat: (name: string, format: true) => unknown;
  compile: (schema: object) => ValidateFunction;
};
type GeneratorAjvConstructor = new (opts: Options) => GeneratorAjv;

// CommonJS on purpose: ajv-formats references its format implementations
// through `require`, which the standalone code keeps, and rolldown bundles a
// CommonJS module (and Node imports one) without further configuration
const require = createRequire(import.meta.url);

const unwrapDefault = <Unwrapped>(moduleValue: unknown): Unwrapped => {
  const withDefault = moduleValue as { default?: Unwrapped };
  return withDefault.default ?? (moduleValue as Unwrapped);
};

export const GENERATED_FILES: Record<OpenapiVersion, string> = {
  '3.0': 'openapi-3.0-validator.cjs',
  '3.1': 'openapi-3.1-validator.cjs',
};

const HEADER =
  '// GENERATED by packages/core/src/spec/generate-validators.ts — do not edit.\n' +
  '// Ajv standalone code for the official OpenAPI meta-schema (issue #76).\n';

// The same Ajv configuration validate.ts used to compile at runtime
export const generateValidator = (version: OpenapiVersion): string => {
  const Ctor = unwrapDefault<GeneratorAjvConstructor>(
    require(version === '3.0' ? 'ajv-draft-04' : 'ajv/dist/2020.js'),
  );
  const addFormats = unwrapDefault<(ajv: GeneratorAjv) => unknown>(require('ajv-formats'));
  const standaloneCode = unwrapDefault<(ajv: GeneratorAjv, validate: ValidateFunction) => string>(
    require('ajv/dist/standalone'),
  );
  const schema: object = require(
    version === '3.0'
      ? '@seriousme/openapi-schema-validator/schemas/v3.0/schema.json'
      : '@seriousme/openapi-schema-validator/schemas/v3.1/schema.json',
  );
  // Strict mode stays off: the official meta-schemas are not strict-mode clean
  const ajv = new Ctor({ strict: false, code: { source: true } });
  addFormats(ajv);
  // Mirrors @seriousme/openapi-schema-validator: media-range is used by the 3.1 schema
  ajv.addFormat('media-range', true);
  return `${HEADER}${standaloneCode(ajv, ajv.compile(schema))}\n`;
};
